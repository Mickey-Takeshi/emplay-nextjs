## PHPの脆弱性（PHP2Shell）で何が起きたか

PHPは、WordPressをはじめ多くのホームページやECサイトを動かしているプログラミング言語です。今回の脆弱性は、ログインなどの認証なしに、外部からサーバー上でプログラムを実行されるおそれがあるものです。悪用されると、サイトの改ざんや顧客情報の持ち出しにつながるおそれがあります。要点は次のとおりです。

| 項目 | 内容 |
| --- | --- |
| 公表 | 2026年10月21日夜（日本時間）にPHP公式が修正版を公開 |
| 識別番号 | CVE-2026-109618、CVE-2026-109619（通称 PHP2Shell） |
| 深刻度 | CVSS v4.0 で 9.2（Critical） |
| 起きうること | 認証なしで、外部からサーバー上のプログラムを実行される |
| 対象 | Webのリクエストを処理するPHP。研究者は、PHP 5.4以降のすべての版が少なくとも1件の影響を受けるとしている |
| 修正版 | 8.5.12／8.4.27／8.3.36／8.2.35 |
| PHP 8.1以前 | 公式の修正版は出ない（7.4・8.0・8.1向けに最小限の修正コードが示されたのみ） |

国内では、国家サイバー統括室が10月21日の昼にXで修正の適用準備を呼びかけ、同日夜には高市首相も「今夜に対応して頂きたい大至急のお願い」と投稿しました。首相の投稿は、適用が難しい場合はサイトの一時停止も有効な策の一つとしています。IPA（情報処理推進機構）とJPCERT/CCも10月22日に注意喚起を出し、IPAは事業責任者や経営層に、更新や移行に必要な予算と体制の確保を求めています。

攻撃の状況も見ておきます。セキュリティ企業の報告によると、公表の前に脆弱性の詳細が外部に漏れており、AmazonやCloudflareなど複数の企業が悪用の試みを観測しています。国内でもロリポップが、脆弱性を狙ったとみられるアクセスを確認したと公表しました（これによる不正アクセスや情報漏えいは確認されていないとしています）。なお、米国CISAの「悪用が確認された脆弱性」のカタログには、10月23日時点で登録されていません。PHPや脆弱性の基本から知りたい方は、[PHPの脆弱性とは？PHP2Shellの影響範囲と古い版が危険な理由を解説](/blog/php-vulnerability-explained)をご覧ください。

## 自社サイトは対象か：3つの質問で判定する

自社が何をすべきかは、次の3つの質問で判定できます。サイトを作ったときの契約書やサーバー代の請求書、委託先への問い合わせで、社内に詳しい人がいなくても答えられます。答えによって、やることと対応する人が変わります。最後に、3つの答えを判定表に当てはめます。

### 質問1：サイトはPHPで動いているか

WordPressで作ったサイトは、PHPで動いています。EC-CUBE、WooCommerce（WordPressのネットショップ機能）、Drupal、Joomla、Magento（Adobe Commerce）なども同じです。HTMLだけで作ったサイトでも、お問い合わせフォームなどの一部にPHPを使っていることがあります。

一方、Shopify、Wix、STUDIO、BASEなどのサービスで作ったサイトは、サーバーやプログラムの管理をサービスの運営会社が行います。

### 質問2：サイトはどこで動いているか

共用のレンタルサーバーか、OSから自分で管理するVPS・クラウドサーバー・自社のサーバーか、サイト作成・ネットショップのサービスかを確かめます。PHP本体を管理する人が、それぞれ異なります。

### 質問3：誰がサイトを管理しているか

自社の担当者か、制作会社・保守会社か、それとも誰もいないか（作った会社と縁が切れている）を確かめます。

3つの答えを、次の表に当てはめてください。

| サイトの置き場所 | PHPの更新を担う人 | 自社がやること |
| --- | --- | --- |
| 共用のレンタルサーバー（エックスサーバー、ロリポップなど） | サーバー会社 | 告知を確かめ、求められた作業（PHPの版の切り替え・動作確認）をする |
| VPS・クラウドサーバー・自社のサーバー | 契約者（自社か委託先） | 修正版への更新が済んだかを至急確かめる |
| サイト作成・ネットショップのサービス | 運営会社 | 運営会社の告知を確かめる（通常、利用者の作業は無い） |
| 分からない | ― | 契約書や請求書から、サーバー会社と制作会社を特定する |

最も急ぐべきは、VPSや自社のサーバーで動いているサイトです。共用のレンタルサーバーと違い、通常はサーバー会社がPHPを更新しないため（管理を任せるプランを除く）、契約者の側で更新しない限り修正は入りません。

## 今日やること5つ

判定ができたら、次の5つを順に進めます。主なレンタルサーバー会社は修正の適用完了を発表しています（エックスサーバーのPHP 5.5以下は、10月22日夜の時点で対応中）。ただし、サイトが正しく動くかの確認は利用者側の作業です。VPSや自社のサーバーで動いている場合は、3の委託先への確認を、ほかの作業より先に済ませてください。

### 1. PHPのバージョンを確認する

WordPressなら、管理画面の「ツール」→「サイトヘルス」→「情報」タブ→「サーバー」で確認できます。サーバー会社の管理画面のPHP設定でも確かめられます。

ただし、番号だけでは対策済みかを判断できない場合があります。ConoHa WINGは、PHPの版を上げずに修正だけを取り込む方法をとったため、サイトヘルスには修正前と同じ番号（例：8.5.11）が表示されることがあると案内しています。共用のレンタルサーバーでは、番号ではなくサーバー会社の告知で確かめてください。

表示が8.1以前なら、今後の脆弱性には修正が出ないおそれがあります（後述）。

### 2. サーバー会社の告知を確かめる

主なレンタルサーバー会社の発表は次のとおりです（10月22日の発表時点）。

| サーバー会社 | 発表の要点 | 利用者へのお願い |
| --- | --- | --- |
| エックスサーバー | PHP 5.6〜8.5は、対象の全サーバーに修正パッチを適用済み。5.5以下は作成・検証中 | 状況により追加の対策を頼む場合がある |
| さくらのレンタルサーバ | 管理画面で選べるすべてのPHPの版で対応を完了 | 緊急の対応は不要。サポート中の最新版への移行を検討する |
| ロリポップ | すべての版に修正を適用し、一部のサーバーで止めていたサイトの表示を13時ごろ再開 | PHP 8.2以降への切り替え、プラグイン・テーマの確認、フォームやファイルのアップロードなどの動作確認 |
| ConoHa WING | 提供中のすべてのPHPの版に修正を適用済み | 版の変更は不要。表示される番号が変わらない場合がある |

エックスサーバーでPHP 5.5以下を使っている場合は、修正の完了を待たずに、サポート中の版への切り替えを委託先やサーバー会社に相談してください。

VPSやクラウドサーバーは、OSやPHPの更新を契約者が行うサービスです。例えばConoHa VPSは、利用者にPHPのアップデートを求める注意喚起を出しています。

告知は各社の公式サイトで確かめ、メールやSMSのリンクは開かないでください。

### 3. 制作会社・保守会社に確認する

サイトを外部に任せている場合は、次の節の文例を使って、対応状況を文書で確認します。

### 4. 間に合わない場合は、サーバー側での一時停止も検討する

すぐに修正を当てられない場合は、サイトの一時停止も選択肢です。IPAも、修正の出ない古い版を使っている場合に、外部からのアクセスの遮断やサービスの一時停止を検討するよう求めています。

注意したいのは、WordPressなどの「メンテナンスモード」では防げないとされている点です。セキュリティ企業のSansecは、PHPがアプリのメンテナンス設定を読み込む前にリクエストを処理するため、と説明しています。止めるときは、サーバー側でPHPが動かないようにする必要があります。共用のレンタルサーバーならサーバー会社に、VPSなどなら委託先に相談してください。

### 5. 修正後の動作を確かめる

修正の適用やPHPの版の切り替えのあとは、サイトが正しく動くかを確かめます。

- トップページと主なページが表示されるか
- お問い合わせフォームが送信でき、自動返信メールが届くか
- 応募フォームの添付など、ファイルのアップロードができるか
- ECサイトなら、カートへの追加から決済まで進めるか
- 管理画面にログインできるか

ロリポップは、安全のためにすべてのPHPの版で一部の機能を無効にしたとして、利用者に動作確認を求めています。

## 委託先に送る確認文例と、回答の読み方

制作会社や保守会社には、確認したいことを具体的に書いて送ります。「大丈夫ですか」とだけ聞くと、何を確かめたのかが分からない返事になりがちです。次の文例は、そのままメールにコピーして使えます。〇〇の部分を自社の情報に置き換えてください。回答の読み方もあわせて示します。

> 件名：PHPの脆弱性（CVE-2026-109618／CVE-2026-109619）への対応状況のご確認
>
> 株式会社〇〇　〇〇様
>
> いつもお世話になっております。株式会社〇〇の〇〇です。
>
> 10月21日に公表されたPHPの脆弱性について、弊社サイト（サイトのURL）の状況を、下記の点でご教示ください。
>
> 1. サイトが動いているサーバー（レンタルサーバーかVPSか、会社名）と、PHPのバージョン
> 2. 今回の脆弱性への対応状況（修正版への更新、またはサーバー会社による修正の適用。完了した日時と、更新後にPHPを再起動して反映を確かめたかも）
> 3. 対応後に、お問い合わせフォームや決済などの動作を確認したか
> 4. PHP 8.1以前の場合、サポート中の版へ移行する見通し
> 5. 不審なアクセスや改ざんの形跡が無いかの確認結果
> 6. 今回の対応が保守契約の範囲内か。範囲外の場合は費用の見積もり
>
> お手数ですが、〇月〇日までにご回答いただけますと幸いです。

### 回答の読み方

| 回答 | 読み方と次の行動 |
| --- | --- |
| 修正版（8.5.12／8.4.27／8.3.36／8.2.35）以降に更新し、PHPを再起動して反映を確かめた | 対応済み。動作確認の結果もあわせて聞く |
| サーバー会社が修正を適用した（番号は変わらない） | 共用のレンタルサーバーでは起こりうる。サーバー会社の告知で確かめる |
| 8.1以前だが、サーバー会社の応急の修正が入った | 今回はしのげても、次の脆弱性には修正が出ないおそれがある。移行を計画する |
| 確認中・分からない | 回答の期限を決めて再確認する。VPSや自社のサーバーなら至急 |
| 返事が無い・保守契約が無い | サーバー会社に契約者として直接問い合わせ、管理を任せる先を探す |

保守契約の範囲外として、費用を求められることもあります。今回の対応がどこまで契約に含まれるのかを今確かめておくと、次の脆弱性のときに慌てずに済みます。

なお、今すぐのPHPの更新は、サーバー会社の管理画面や、現在の委託先で進めるのが最も早い方法です。そのうえで、委託先と連絡が取れない、保守を任せる先が無い、PHPを上げたら表示や機能が崩れたといった場合は、EMPLAYに[お問い合わせ](/contact)ください。サイトの状況を伺い、修正や移行、保守の進め方をご提案します。

## PHP 8.1以前のサイトはどうするか

PHP 8.1以前は、開発元のサポートがすでに終わっています。今回もPHP公式から修正版は出ず、7.4・8.0・8.1向けに最小限の修正コードが示されただけで、それより古い版には何も出ていません。

サーバー会社が独自に修正を当てた例もありますが、ロリポップはこれを応急的な対策とし、今後の脆弱性には対応できない可能性があると説明しています。IPAも、サポートが続いている版や移行先の製品・サービスに移るよう求めています。

移る先の版にも期限があります。PHPの各版のセキュリティサポートの終了日は次のとおりです。

| PHPの版 | セキュリティサポートの終了日 |
| --- | --- |
| 8.1以前 | 終了済み |
| 8.2 | 2026年12月31日 |
| 8.3 | 2027年12月31日 |
| 8.4 | 2028年12月31日 |
| 8.5 | 2029年12月31日 |

8.2も2か月あまりで終わるため、移るなら8.3以降が現実的です（テーマやプラグインの対応が前提）。移行の方法は、サイトの状態で3つに分かれます。

| 方法 | 向いているサイト | 注意点 |
| --- | --- | --- |
| PHPの版を上げる | WordPress本体・テーマ・プラグインが新しい版に対応している | バックアップを取り、検証用の環境で試してから切り替える |
| 直してから上げる | 独自のプログラムや古いプラグインの一部が動かない | 動かない部分の洗い出しと修正に時間がかかる |
| 作り直す | 長く更新されていないテーマ・プラグインが多い。デザインや内容も古い | 費用と期間はかかるが、保守しやすい形に整えられる |

判断の目安は、テーマとプラグインの更新が続いているかどうかです。何年も更新されていないものが多ければ、PHPの版だけを上げても、次の不具合や脆弱性につながりやすくなります。作り直すかどうかは、[ホームページが古いままだとどうなる？リニューアル判断チェック](/blog/outdated-website-risks)も参考にしてください。

古いPHPからの移行や作り直しは、EMPLAYの[ホームページ制作サービス](/service/hp)でもご相談いただけます。

## ECサイト・会員サイトが特に確かめること

顧客の個人情報や注文の情報を扱うサイトは、被害が起きたときの影響が大きくなります。修正の適用に加えて、次の点も確かめてください。

EC-CUBEの開発元も10月22日に、至急の対応を求める案内を出しました。サーバーを自社や委託先で管理している場合は、修正版の適用と、反映の確認を求めています。EC-CUBE本体やプラグインを更新しても、サーバー側のPHPは修正されない点にも注意が必要です。PHPを更新する際は、購入や決済などの主な機能が動くかの確認も欠かせません。

- **侵害の形跡が無いか**：身に覚えのない管理者アカウントやファイル、ページの書き換え、別のサイトへの転送、サーバー会社やGoogleからの警告が無いかを、委託先に確かめてもらう。形跡があっても、調査に必要な記録が消えるため、慌ててデータを消さない
- **形跡があったときの相談先**：サーバー会社と委託先に加えて、セキュリティの専門会社に調査を依頼する。IPAの「情報セキュリティ安心相談窓口」でも相談を受け付けている
- **個人情報の漏えいのおそれ**：不正アクセスによる漏えいのおそれがある場合、人数にかかわらず、個人情報保護委員会への報告と、原則として本人への通知が必要になる。詳しくは[個人情報保護法対応ガイド](/blog/personal-data-protection-guide)を参照
- **カード決済**：決済を外部の決済代行会社に任せていても、入力画面が改ざんされればカード情報が盗まれるおそれがある。不審な点があれば決済代行会社にも連絡する

## 便乗詐欺に注意する

大きな脆弱性が報じられると、それに便乗した詐欺も出てきます。SNSでは、PHPの対策を口実にログインを促すメールが届いたという投稿も見られます。サーバーや管理画面のログイン情報が盗まれると、脆弱性とは別の経路でサイトを乗っ取られるおそれがあります。

- サーバー会社や制作会社を名乗り、「至急ログインして対策を」と促すメールやSMSは、リンクを開かずに公式サイトから確かめる
- 突然届く「無料で脆弱性を診断します」「今すぐ対策しないとサイトが止まる」といった連絡には、すぐに応じず、契約中の会社に確かめてから判断する
- 管理画面のIDやパスワードを、電話やメールで聞かれても答えない

手口と社内での防ぎ方は、[フィッシング詐欺対策ガイド](/blog/phishing-prevention-guide)で詳しく解説しています。

## これからの備え：保守体制を見直す

今回の脆弱性の主な発見者は、AIを使っていました。OpenAIはセキュリティ企業のCalifが同社のAIで重大な欠陥を見つけたと発表し、独自に発見したWizも複数のAIを併用したと公表しています。AIの活用が進めば、見つかる脆弱性が増え、更新が必要になる場面も増えると考えられます。詳しくは[AIによるサイバー攻撃とは？脆弱性の発見が加速する今、企業がやるべき対策](/blog/ai-cyber-attack-risks)で解説しています。

サイトは作って終わりではなく、更新を続ける体制があるかが、これまで以上に問われます。保守契約では、次の点を確かめておきましょう。

- PHP・CMS本体・プラグインの更新が契約に含まれるか。頻度と費用はどうか
- 緊急の脆弱性が出たときの連絡の方法と、対応までの時間
- バックアップの頻度と、復旧の手順
- PHPの版のサポート期限を、誰が把握しているか

保守の内容と費用の目安は[ホームページ保守費用の相場](/blog/website-maintenance-cost-guide)、PHP以外の基本対策は[WordPressのセキュリティ対策](/blog/wordpress-security-hardening)で解説しています。

## よくある質問

### サイトを見ているだけの一般の利用者も、何かする必要がありますか？

原則として必要ありません。今回の脆弱性はサイトを動かすサーバー側の問題で、対応するのはサイトの運営者です。ただし、便乗詐欺のメールやSMSには注意してください。

### 共用のレンタルサーバーなら、何もしなくて良いですか？

PHP本体の修正はサーバー会社が行います。ただし、PHPの版の切り替えや動作確認を利用者に求めている会社もあるため、ご利用中の会社の告知を確かめてください。

### WordPressを最新版にすれば大丈夫ですか？

今回の脆弱性は、WordPressではなく、その土台のPHPにあります。WordPressを最新にしても、PHPが修正されていなければ対策になりません。両方を最新に保つことが基本です。

### 更新までの間、設定で防ぐ方法（緩和策）はありますか？

PHP公式は、一部の設定の変更で攻撃経路の一部を塞げるとしていますが、完全な対策は更新だけとしています。設定の変更はサーバーの管理者の作業で、共用のレンタルサーバーではサーバー会社が、VPSなどでは自社か委託先が判断します。まずは更新の予定を確かめてください。

### サイトヘルスに表示されるPHPのバージョンが、修正版より前の番号です。危険ですか？

番号だけでは判断できません。共用のレンタルサーバーでは番号を変えずに修正を取り込むことがあるため、サーバー会社の告知で確かめてください。VPSや自社のサーバーなら、修正版への更新か、OSの提供元が出した修正の適用が必要です。

### サイトを一時的に止めるべきですか？

修正をすぐに当てられない場合は、選択肢の一つです。メンテナンスモードでは防げないとされているため、止め方はサーバー会社や委託先に相談してください。ECサイトは売上への影響も含めて判断します。

### Shopify・Wix・STUDIOなどで作ったサイトも対象ですか？

これらのサービスでは、サーバーやプログラムの管理を運営会社が行うため、利用者が作業することは通常ありません。気になる場合は、運営会社の告知を確かめてください。

## まとめ

- やることは、サイトの置き場所と管理者で決まる
- 共用のレンタルサーバーは、サーバー会社の告知を確かめ、求められた作業と動作確認をする
- VPSや自社のサーバーは、修正版への更新が済んだかを至急確かめる
- PHP 8.1以前は公式の修正が出ない。8.2も2026年12月31日で終わるため、8.3以降への移行を計画する
- 委託先には具体的に文書で確認し、保守契約の範囲も見直す

古いPHPのサイトの移行やリニューアルは、EMPLAYの[ホームページ制作サービス](/service/hp)でご相談いただけます。PHPの更新後に表示や機能が崩れた、公開後の保守を任せる先が無いといったお悩みも、「何から確かめればよいか」という段階から[お問い合わせ](/contact)ください。

