## AIで脆弱性の発見が速くなっている

ここ数年で、AIがソフトウェアの脆弱性を自ら見つける事例が相次いでいます。専門家が時間をかけて探していた欠陥を、AIが短時間で大量に洗い出せるようになりつつあります。主な発表は次のとおりです（件数や性能は各社の自己申告）。

| 時期 | 発表元 | 内容 |
| --- | --- | --- |
| 2024年11月 | Google | AIの「Big Sleep」が、実際に広く使われているソフト（SQLite）の脆弱性を見つけたと発表 |
| 2025年8月 | 米国防高等研究計画局（DARPA） | AIの競技会の決勝で、用意された脆弱性63件のうち54件を発見し、43件を修正 |
