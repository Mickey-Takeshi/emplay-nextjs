## AIのセキュリティリスクとは：2つの側面

AIのセキュリティリスクは、大きく2つに分けられます。一つは、AIが攻撃に使われ、攻撃が速く・安く・巧妙になるリスクです。もう一つは、社内でAIを使うときに情報が漏れたり、誤った出力を信じたりするリスクです。IPAの「情報セキュリティ10大脅威 2026」（組織編）でも、「AIの利用をめぐるサイバーリスク」が初めて選ばれ、3位に入りました。

| 側面 | 具体例 | 主な対策 |
| --- | --- | --- |
| 攻撃に使われる | 脆弱性の発見や攻撃の準備が速くなる。だましのメールや偽サイトが巧妙になる | 更新を速くする、ログインを守る、確認のルールを決める |
| 使う側のリスク | 入力した情報の漏えい、出力の鵜呑み、AIへの指示の乗っ取り | 利用ルールを決める、出力を人が確かめる |

