## 発見が速くなると、なぜ企業のリスクが高まるのか

脆弱性の発見が速くなること自体は、守る側にとって良いことです。問題は、修正版が公開されてから、攻撃が始まるまでの時間が短くなることです。修正版が出ると、攻撃者は修正の中身から欠陥を割り出し、まだ更新していないサイトを狙います。

PHP2Shellで公表前から攻撃の試みを観測したAmazonは、AIを使った解析で修正の中身から攻撃方法を割り出す手間が下がり、公表から数時間、あるいは数分で動く攻撃者が増えると見ています。見つかる脆弱性が増え、狙われるまでの時間も短くなれば、更新を後回しにするサイトほど危険が高まります。

英国の政府機関であるAI Security Institute（AISI）は、Anthropicの未公開のAIを評価し、企業のネットワークへの攻撃を模した32段階の演習を、AIとして初めて最後までやり遂げたと報告しました（10回中3回）。一方でAISIは、守りの固い環境で攻撃が成功するかは断定できないとし、更新の適用などの基本対策を重視するよう呼びかけています。

## 攻撃者もAIを使い始めている

AIを悪用した攻撃も、すでに報告されています。AIの開発企業や大手IT企業は、自社のAIが悪用された事例を公表しており、攻撃の準備から実行までの多くをAIに任せる例も出てきました。主な例を挙げます。

- **AIに作業の大半を任せた攻撃**：Anthropicは2025年11月、中国政府系と同社がみるグループが、同社のAIを悪用して約30の組織を狙ったと公表しました。成功は一部にとどまったものの、作業の8〜9割をAIが担ったとしています
- **AIで作られたとみられる攻撃コード**：Googleの脅威分析チームは2026年5月、AIを使って開発されたと同社がみる、未修正の脆弱性を突く攻撃を初めて確認したと報告しました
- **だましのメールや偽サイト**：フィッシング対策協議会への報告は、2026年9月だけで9万4,661件に上りました。同協議会は、AIに作らせたとみられるメールが多く見られることや、実在のサイトの写真や屋号を流用した偽のECサイトが増えていることを報告しています

現時点では、AIがまったく新しい種類の攻撃を生み出しているというより、これまでの攻撃を速く、安く、大量に行えるようになっていることが、大きな変化だと考えられます。国家サイバー統括室も、2026年5月の重要インフラ事業者向けの注意喚起で、AIの高度化によって攻撃の速度や規模が大きく増すおそれがあると警告しています。

## 中小企業がやるべき対策7つ

AIを使った攻撃に、まったく新しい対策が必要なわけではありません。速くなる攻撃に合わせて、基本の対策を速く、漏れなく回すことが要点です。ホームページやECサイトを運営する企業は、次の7つを確かめてください。

| 対策 | やること |
| --- | --- |
| 1. 更新を速くする | 保守契約で、更新の範囲と対応までの時間を決める。使える場面では自動更新を使う |
| 2. 使っているソフトと版を把握する | CMS・プラグイン・PHPなどの版と、サポートの期限を一覧にする |
| 3. サポート切れを放置しない | 期限が近いものは移行を計画する。PHP 8.2は2026年12月31日に終わる |
| 4. ログインを守る | 管理画面やメールに多要素認証を設定し、管理画面へのアクセスを制限する |
| 5. バックアップと復旧の手順を持つ | 定期的にバックアップを取り、戻す手順を確かめておく |
| 6. だましに備える | 送金やログインの依頼は別の経路で確認する。送信ドメイン認証（DMARC）を設定する |
| 7. AIの利用ルールを決める | 入力してよい情報、使ってよいツール、出力の確かめ方を決める |

最も効くのは1〜3です。PHP2Shellでも、正式な修正版が出たのはサポートが続く8.2以降だけでした。

### 更新を速くするには

共用のレンタルサーバーでは、PHPなどの土台の更新はサーバー会社が行います。今回も、主なサーバー会社は公表から1日ほどで修正の適用を発表しました（一部の古い版を除く）。ただし、PHPの版の切り替え（サポート中の版への移行）と更新後の動作確認は、自社か委託先が行います。CMSやプラグインの更新、VPSや自社のサーバーの更新も、自社か委託先の仕事です。保守契約では、重大な脆弱性が出たときに何日以内に対応するのか、夜間や休日はどうするのかまで決めておきましょう。

WAF（Webアプリケーションファイアウォール）のように攻撃の通信を止める仕組みも役立ちます。ただし、PHP2Shellで防御のルールを用意したCloudflareも、WAFは補助であり、PHPの更新が必要だとしています。

### 使っているソフトと期限を把握するには

まずは、サイトを動かしているものを一覧にします。CMSとその版、プラグインとテーマ、PHPの版、サーバーの種類、それぞれのサポート期限、更新を担う人の6つが分かれば十分です。自社で分からない部分は、委託先に聞いて埋めます。一覧は年に数回見直し、期限が1年以内に迫ったものから移行を計画します。自社サイトの確かめ方は、[PHPの脆弱性対応、自社サイトは何をすれば良い？確認方法と委託先への連絡文例](/blog/php-vulnerability-response)で詳しく解説しています。

だましへの備えは[フィッシング詐欺対策ガイド](/blog/phishing-prevention-guide)、PHPの脆弱性の基本は[PHPの脆弱性とは？](/blog/php-vulnerability-explained)もあわせてご覧ください。

## AIを使う側のリスクにも備える

社内でAIを使う場合のリスクも押さえておきます。代表的なものは、入力した顧客情報や社外秘の情報が漏れること、AIの誤った出力をそのまま使うこと、AIへの指示を外部から乗っ取られること（プロンプトインジェクション）です。プロンプトインジェクションは、AIのアプリの脆弱性をまとめたOWASPの一覧（2025年版）でも、最初の項目に挙げられています。

いずれも、使ってよいツールと入力してよい情報を決め、重要な出力は人が確かめるというルールで、多くを防げます。具体的な決め方は、[生成AIの情報漏洩リスクと対策](/blog/generative-ai-data-leakage-prevention)と[AIガバナンスとは？](/blog/ai-governance-guide)で解説しています。

## よくある質問

### AIを使えば、誰でもサイバー攻撃ができるようになるのですか？

攻撃の準備にかかる手間が下がっているのは確かです。Anthropicは、高度な攻撃に高度な攻撃者はもう要らなくなったと分析しています。一方で、更新や多要素認証などの基本の対策は、AIを使った攻撃にも効きます。

### 中小企業も狙われますか？

狙われます。攻撃の多くは自動化されており、広く使われているソフトの脆弱性は、会社の規模に関係なく狙われます。PHP2Shellでも、規模を問わず、PHPで動くすべてのサイトに対応が求められました。

### AIで守ることはできますか？

できます。脆弱性の発見や修正、不審な通信の検知などで、AIの活用が進んでいます。中小企業にとって現実的なのは、修正を速く当ててくれるサーバー会社や保守の委託先を選び、自社では更新を後回しにしない体制を整えることです。

### AIで作られただましのメールは見分けられますか？

見た目だけで見分けるのは難しくなっていると考えられます。日本語の不自然さに頼らず、送金やログインの依頼は、メールのリンクではなく、電話や公式サイトなど別の経路で確かめることを社内のルールにしてください。

### 生成AIを社内で使うのは危険ですか？

使い方しだいです。入力してよい情報や使ってよいツールを決めずに使うと、情報の漏えいや誤った判断につながるおそれがあります。ルールを決めて使えば、リスクを抑えながら業務に役立てられます。

## まとめ

- AIのセキュリティリスクには、攻撃に使われるリスクと、使う側のリスクの2つがある
- AIで脆弱性の発見が速くなり、修正版の公開から攻撃までの時間も短くなるおそれがある
- 攻撃者によるAIの悪用も報告されている。大きな変化は、既存の攻撃が速く・安く・大量になることだと考えられる
- 最も効く対策は、更新を速くすること、使っているソフトを把握すること、サポート切れを放置しないこと

AIの時代は、ホームページを「作って終わり」にせず、更新を続けられる体制を持つことが一層大切になります。古いシステムのサイトの作り直しは、EMPLAYの[ホームページ制作サービス](/service/hp)でご相談いただけます。公開後の保守の進め方を見直したい場合も、[お問い合わせ](/contact)からお気軽にどうぞ。

