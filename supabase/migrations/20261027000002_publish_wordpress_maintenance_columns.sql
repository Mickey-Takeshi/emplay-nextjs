## 最優先はドメイン、次にサーバーとメール

サイトを構成するものは一つの契約ではありません。優先順位を付けずに作業すると、WordPressへ入れてもドメインの更新ができない、サーバーを変更したらメールが止まる、といった問題が起きます。

| 優先度 | 対象 | 止まった場合の影響 |
| --- | --- | --- |
| 1 | ドメイン | URLとメールアドレスが使えなくなる可能性がある |
| 2 | DNS・サーバー | サイト表示、フォーム、メールの配送に影響する |
| 3 | CMS・データ | 更新やバックアップ、改修ができない |
| 4 | メール・フォーム | 問い合わせを受け取れない、送信元認証が崩れる |
| 5 | 計測・外部連携 | アクセス分析、広告計測、地図、予約等が確認できない |

特にドメインは、第三者が同じ文字列をすぐ取り直せるとは限らず、失効後の回復にも制約があります。JPRSは、登録者・登録組織の情報を正確かつ最新にし、制作会社など第三者の連絡先になっている場合は登録者自身の連絡先へ変更するよう案内しています。

