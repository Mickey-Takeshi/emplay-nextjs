## まず確認する7つの質問

見積もりを取る前に、次の質問へ答えます。「分からない」が多い場合は、それ自体が管理上のリスクであり、初期調査の対象です。

1. WordPress本体をサポート中の版へ更新できるか
2. PHPをサポート中の版へ上げられるか
3. テーマと主要プラグインは現在も更新されているか
4. 独自機能のソースコードと仕様が残っているか
5. ドメイン、サーバー、CMS、計測の管理権限が自社にあるか
6. ファイルとデータベースのバックアップを取得・復元できるか
7. 問い合わせ、予約、決済等の重要機能をテストできるか

この7項目は、単に「サイトが表示されるか」より重要です。表示できていても、更新できないサイトは、新しい脆弱性や外部サービスの仕様変更へ対応できません。

## 改修・段階移行・再構築の違い

二者択一ではなく、緊急対応と長期計画を分ける「段階移行」もあります。

| 選択肢 | 向いている状態 | 主な作業 | 注意点 |
| --- | --- | --- | --- |
| 改修 | 更新経路と管理情報があり、問題箇所が限定的 | 更新、プラグイン置換、コード修正、表示改善 | 古い構造を残すため、次の更新負担を確認する |
| 段階移行 | すぐ全面刷新できないが、現状の危険を先に減らしたい | 不要機能停止、PHP移行、重要ページから移す | 旧新環境を並行管理する期間が発生する |
| 再構築 | 更新停止、権限不明、独自実装の老朽化、複数課題がある | 要件整理、情報設計、実装、移行、運用設計 | コンテンツ移行、URL、フォーム、計測の引き継ぎが必要 |

「セキュリティ上不安だからすぐ作り直す」という判断も危険です。新サイトの完成まで旧サイトは公開され続けます。まず現状を調べ、更新、不要機能の停止、アクセス制限など、公開中のリスクを減らす処置を並行します。

## 改修を選びやすいケース

### 更新対象が特定できる

WordPress本体、PHP、テーマ、プラグインの版が把握でき、サポート中の版への更新手順を作れる場合です。テスト環境で更新し、問題が出る部品だけを置き換えられるなら、全面再構築より小さく進められます。

### 独自機能が少なく、代替手段がある

お問い合わせや更新機能が標準的で、古いプラグインを現行製品へ置き換えられる場合です。置き換え後のデータ移行と運用方法まで確認します。

### 情報設計とURLを維持したい

検索流入があるページや、外部からリンクされるURLを保ちながら、内部の仕組みだけ更新したい場合です。ただし再構築でもURLを維持できるため、「SEOのために古いWordPressを残す」必要はありません。

## 再構築を選びやすいケース

### 更新が複数世代止まっている

WordPress、PHP、テーマ、プラグインを一度に上げると、どこで不具合が出たか切り分けにくくなります。2026年10月のPHP2Shellの注意喚起でも、IPAは修正版が提供されない版について、サポート中の版への更新や対策済みサービスへの移行を検討するよう求めました。

古い版を動かし続けるための修正を重ねるより、サポートされる構成へ移した方が、次回以降の更新を標準化できます。

### 管理権限・仕様・ソースが不足している

制作会社と連絡が取れない、独自機能の仕様がない、管理者が退職したといった状態です。まず[HP引き継ぎ手順](/blog/website-management-handover-guide)で権限回復を試します。回復できない部分が多いほど、既存環境を安全に直す見積もりは不確実になります。

### 問い合わせや計測まで含めて見直す必要がある

デザインだけでなく、フォームが届かない、スマートフォンで読みにくい、更新担当者が使えない、GA4や広告計測が不明といった課題が重なっている場合です。個別修正を積み上げるより、要件を整理して一つの公開手順にまとめる方が、検収しやすくなります。

### 使っていない機能が多い

停止したキャンペーン用LP、退職者のアカウント、更新されないプラグイン、不要な会員機能などは、維持するほど管理対象が増えます。再構築時に「必要な機能だけ」に減らすことは、将来の更新と点検を簡単にします。

## セキュリティ事故をきっかけに判断するとき

改ざんや情報漏えいの疑いがある場合、再構築の検討だけで現在のサイトを放置してはいけません。個人情報保護委員会は、Webサイトの改ざんによって入力された個人データが第三者へ送信された場合、漏えい等として報告対象になり得ると示しています。

疑いがあるときは、次の順に進めます。

1. 保守契約や社内手順に従って、影響拡大を防ぐ
2. ログ、ファイル、送信先など調査に必要な記録を保全する
3. 対象データ、期間、利用者への影響を確認する
4. 法令・ガイドラインにもとづく報告と本人通知を判断する
5. 侵入経路と管理上の原因を直したうえで、復旧・再構築を選ぶ

緊急時の作業は、平常時の保守と別の専門性・体制が必要です。既存の保守運用プランで駆除・復旧を依頼する場合も、受付条件と作業範囲を確認します。

## 費用は「作る費用」と「不確実性を減らす費用」に分ける

改修と再構築の見積もりを比べるとき、金額だけを横に並べると判断を誤ります。既存サイトの調査や互換性テストが見積もりに含まれているかを確認してください。

| 費用項目 | 改修 | 再構築 |
| --- | --- | --- |
| 現状調査 | 必須。古い構成ほど比重が大きい | 移行対象と権限の確認に必要 |
| 設計 | 変更箇所に限定しやすい | 情報設計・運用設計を含めて見直す |
| 実装 | 問題箇所の修正・置換 | 新環境の構築とテンプレート実装 |
| データ移行 | 小さいことが多い | 記事、画像、フォーム、URLの移行が必要 |
| テスト | 既存機能への影響を広く確認 | 新旧比較、リダイレクト、計測を確認 |
| 公開後 | 古い構造の残存リスクを管理 | 新しい保守手順を定着させる |

改修では、調査後に追加修正が増える可能性があります。再構築では、初期費用は大きくなりやすい一方、対象範囲を決めやすく、保守費用の見通しを立てやすくなります。見積書には、前提条件、対象外、追加費用になる条件、戻し方を書いてもらいます。

ホームページ制作の初期費用は要件で変わります。EMPLAYでは、ページ数、機能、移行量、保守範囲を確認して個別に見積もります。保守費用の考え方は[ホームページ保守費用の相場](/blog/website-maintenance-cost-guide)も参照してください。

## 判断を見積もりに落とす依頼書

候補会社へは「改修案と再構築案の両方をください」だけでなく、次の条件を渡します。

- 現在困っていることと、事業上止められない機能
- ドメイン、サーバー、WordPressの権限状況
- WordPress、PHP、テーマ、プラグインの版
- 月に行う更新と、今後追加したい内容
- 残したいページ・URL・検索流入
- フォーム、予約、決済、会員、外部連携
- 公開希望時期と、社内の確認担当者
- 公開後に必要な保守、監視、緊急時の条件

同じ情報を渡し、改修・段階移行・再構築それぞれの「できること」「残るリスク」「期間」「費用」「保守方法」を出してもらうと比較できます。

## 実施の進め方

1. ドメイン、サーバー、CMS、データ、外部連携を棚卸しする
2. バックアップを取り、テスト環境を用意する
3. サポート期限と更新可否を調べ、問題を重要度順に分ける
4. 改修・段階移行・再構築の3案で、残るリスクと総費用を比べる
5. 公開中のサイトに必要な暫定対策を実施する
6. 選んだ案をテストし、フォーム・計測・URLを含めて公開する
7. 更新頻度、バックアップ、監視、緊急時、契約終了時を保守契約にする

制作と保守を別会社へ依頼する場合も、公開後の責任分界を公開前に決めます。「作った会社」と「保守する会社」の間で対象外が生まれないよう、引き継ぎ資料と検収項目を共有します。

## よくある質問

### デザインが古いだけなら改修でよいですか？

内部の更新状態が良ければ、デザイン改修で済む可能性があります。ただし見た目を変える前に、WordPress・PHP・テーマ・プラグインの更新可否と管理権限を確認してください。

### WordPressをやめた方が安全ですか？

仕組みだけで安全性は決まりません。WordPressでも、更新、権限、バックアップ、監視、緊急対応を継続できれば運用できます。自社でその体制を持てない場合は、保守を外注するか、管理範囲の小さいサービスへ移る選択肢があります。

### 再構築すると検索順位は下がりますか？

URL、本文、タイトル、内部リンク、構造化データ、リダイレクト、表示速度を適切に移行すれば、影響を抑えられます。公開前後にURL一覧を照合し、404や計測漏れを確認することが重要です。

### まず一部だけ直し、後から作り直せますか？

可能です。暫定改修が新サイトでも使えるか、捨てる作業になるかを区別してください。たとえば権限整理、バックアップ、コンテンツ棚卸しは再構築にも生かせますが、古いテーマ専用の大規模修正は使い捨てになることがあります。

## まとめ

- 改修か再構築かは、見た目ではなく更新可否・管理権限・テスト可能性・今後の運用で決める
- 更新経路が明確で問題が限定的なら改修、複数世代の停止や管理不明が重なるなら再構築を検討する
- 全面刷新まで時間がかかる場合は、現在のリスクを先に減らす段階移行がある
- 見積もりでは、現状調査、追加費用の条件、残るリスク、公開後の保守を同じ条件で比べる
- 再構築中も旧サイトの更新・権限・バックアップを放置しない

EMPLAYでは、現在のWordPressを調査し、改修と再構築の選択肢を同じ基準で整理します。[WordPressサイトの見直し](/service/hp/wordpress-renewal?intent=security)または[お問い合わせ](/contact?topic=wordpress-renewal&intent=security)から、分かる範囲の管理情報をお知らせください。

