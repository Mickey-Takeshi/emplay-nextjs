## 連絡が取れないときの引き継ぎ手順

### 1. 契約書・請求書・社内メールを集める

制作時の見積書、契約書、納品書、月額保守の請求書、カード明細を集めます。サービス名が分からなくても、請求元やメールの差出人からドメイン・サーバー会社を特定できます。退職者の会社メールは、社内規程に沿って管理者が検索します。

### 2. 契約名義と更新期限を確認する

ログインできることと、自社が契約者であることは別です。ドメインとサーバーについて、会社名義か、制作会社名義か、個人名義かを確認します。期限が近い場合は、移管より先に更新を確実にします。

### 3. 現在の会社へ書面で引き継ぎを依頼する

電話だけでなく、メールや書面で必要な資産を一覧にし、回答期限を示して依頼履歴を残します。伝える内容は、契約者名、対象ドメイン、必要な管理情報、希望する連絡方法です。パスワードを平文メールで送らせず、アカウント招待や安全な共有方法を指定します。

### 4. サービス提供会社へ本人確認の方法を聞く

制作会社から返答がない場合、ドメインやサーバーの提供会社へ、自社が契約者・登録者であることを確認する手続きを問い合わせます。必要書類や扱いは各社で異なります。第三者になりすましてパスワード再発行を試さず、正式な窓口を使います。

### 5. 変更前に現状を保存する

権限を確保できたら、次の順に保存します。

1. DNSレコードとドメイン登録情報
2. サーバー上の全ファイルとデータベース
3. WordPressのユーザー、テーマ、プラグイン一覧
4. フォーム設定と通知先
5. 計測タグ、外部連携、定期実行処理
6. 主要ページとフォームの動作記録

保存前に大きな更新やサーバー移転を始めると、元へ戻せなくなることがあります。先に現状を複製し、テスト環境で確認します。

### 6. 新しい管理者を追加してから古い権限を整理する

新しい会社や社内担当者の個別アカウントを作り、ログインと必要操作を確認します。その後、不要になった旧担当者の権限を無効化し、共有パスワードを変更し、二要素認証と復旧先を自社管理へ移します。

いきなり唯一の管理者を削除すると復旧できなくなるため、「新規追加→動作確認→旧権限停止」の順にします。

### 7. サイトと問い合わせを実際に確認する

引き継ぎ後は、トップページの表示だけで終わらせません。主要ページ、スマートフォン表示、問い合わせ送信と受信、自動返信、検索エンジン向け設定、アクセス計測、予約・決済等を確認します。期限と担当者を管理台帳に残し、次回の属人化を防ぎます。

## 引き継ぎが難しくなるサイン

次の状況が一つでもあれば、通常の保守開始より先に初期調査が必要です。

- ドメインの登録者が制作会社や退職者の名義になっている
- ドメイン・サーバーの支払元が分からない
- 管理画面が共通IDで、誰が使っているか分からない
- 二要素認証が退職者の電話番号に届く
- ファイルとデータベースのバックアップがない
- WordPress、PHP、テーマ、プラグインが長期間更新されていない
- 問い合わせの送信先や保存場所を誰も把握していない
- 制作データや有料ライセンスの所有者が不明

更新が止まったサイトには、既知の脆弱性が残っている可能性があります。2026年の注意喚起でも、IPAは公開中のWebアプリケーションを把握し、ログや未適用パッチを確認するよう求めています。権限を取り戻した後は、[WordPressのセキュリティ対策](/blog/wordpress-security-hardening)に沿って現状を点検してください。

## 次の契約で属人化を防ぐ

引き継ぎが終わったら、同じ問題を繰り返さない管理ルールを作ります。

- ドメインとサーバーは原則として自社名義で契約する
- 会社の共有管理メールを使い、個人のメールだけに依存しない
- 作業者ごとに個別アカウントを発行し、権限を必要最小限にする
- 資産一覧、更新日、担当者、復旧先を四半期ごとに確認する
- バックアップの取得だけでなく復元を試す
- 契約書にデータ返却と次の会社への引き継ぎを含める

外注先を選ぶ際の契約項目は[WordPress保守を外注する会社の選び方](/blog/wordpress-maintenance-outsourcing-guide)で確認できます。

## よくある質問

### WordPressの管理画面に入れれば引き継ぎできますか？

十分ではありません。ドメイン、DNS、サーバー、メール、バックアップ、計測・外部連携を別々に確認する必要があります。WordPress管理者だけでは、ドメインの更新やサーバー障害の復旧ができないことがあります。

### 制作会社名義のドメインは取り戻せますか？

登録者・契約内容によって異なります。まず登録情報、契約書、請求記録を確認し、現在または変更先の管理事業者へ正式な手続きを問い合わせてください。JPドメインでは、登録者が管理指定事業者を変更できる仕組みがあります。

### ログイン情報が一つもない場合、作り直すしかありませんか？

すぐに作り直すとは限りません。契約名義を確認できれば、サービス提供会社の本人確認で権限を回復できる場合があります。回復できない資産と、回復にかかる期間を整理してから、移管・改修・再構築を比較します。

### 引き継ぎ中もサイトを公開したままにできますか？

多くの場合は可能です。現在のDNSやサーバーを変更せず、先に権限とバックアップを確保します。切り替えが必要な場合は、テスト環境、切り戻し手順、メールへの影響を確認してから実施します。

## まとめ

- 連絡が取れないときは、作り直しより先にドメインとサーバーの名義・期限を確保する
- Webサイトは、ドメイン、DNS、サーバー、CMS、メール、計測を別々の資産として棚卸しする
- 正式な本人確認を使い、現状を保存してから権限を変更する
- 新しい管理者を追加・確認してから、古い権限を停止する
- 引き継ぎ後は自社名義、個別アカウント、資産台帳、復元テストで属人化を防ぐ

管理先が分からない状態でも、契約書や請求書から確認項目を整理できます。EMPLAYの[WordPressサイト見直し](/service/hp/wordpress-renewal?intent=maintenance)では、現状調査から改修・再構築・保守の進め方をご提案します。[お問い合わせ](/contact?topic=wordpress-renewal&intent=maintenance)時に「管理会社と連絡が取れない」とお書きください。

