## 結論：保守会社は「平常時・変更時・緊急時・終了時」の4場面で比べる

良い保守契約は、日常の更新作業だけでなく、変更を加えるときの検証、異常が起きたときの連絡、契約を終えるときのデータ返却まで明確です。逆に「WordPressを保守します」という一文だけでは、責任範囲を判断できません。

比較するときは、次の4場面に分けて質問すると抜けが減ります。

| 場面 | 確認すること |
| --- | --- |
| 平常時 | WordPress・テーマ・プラグイン・PHPの確認頻度、バックアップ、稼働確認、月次報告 |
| 変更時 | テスト環境の有無、更新前後の確認、フォームや予約機能のテスト、元に戻す手順 |
| 緊急時 | 受付時間、一次回答までの目安、調査・隔離・復旧の範囲、追加費用、連絡経路 |
| 終了時 | ファイル・DB・アカウント・設定一覧の返却、次の会社への引き継ぎ、削除証明 |

緊急時の駆除・復旧や継続監視は、通常の制作費に自動で含まれるものではありません。EMPLAYでも、これらは保守運用プランを契約する場合に、監視の粒度、受付条件、作業範囲を事前に決めて提供します。

## WordPress保守で依頼できる主な業務

保守の内容は会社ごとに異なります。見積もりを依頼する前に、自社が必要とする項目を選び、同じ条件で比較してください。

### 1. WordPress・テーマ・プラグインの更新

更新通知が出たらすぐ本番へ適用するのではなく、互換性と影響範囲を確認します。問い合わせフォーム、予約、会員、決済など事業に直結する機能がある場合は、テスト環境で更新してから本番へ反映する流れが必要です。

WordPress公式も、本体を更新する前にデータベースとファイルをバックアップするよう案内しています。「更新代行」に、事前バックアップ、テスト、更新後確認、問題時の切り戻しが含まれるかを確かめましょう。

### 2. PHP・サーバー環境の確認

WordPressが新しくても、サーバー側のPHPが古いままでは脆弱性への修正版を受けられないことがあります。2026年10月に公表されたPHP2Shellでは、IPAがサポート中の版への更新や、対策済みの製品・サービスへの移行を呼びかけました。

保守会社に、現在のPHPの版、サポート終了日、移行先、テーマやプラグインとの互換性確認まで依頼できるかを聞きます。版の確認方法と移行判断は[PHP 8.2のサポート終了とWordPressサイトの移行判断](/blog/php-support-end-migration)で解説しています。

### 3. バックアップと復元確認

バックアップは「取っている」だけでは不十分です。ファイルとデータベースの両方が対象か、保存先が本番サーバーと分かれているか、保存期間は何日か、実際に戻せるかを確認します。

特に重要なのは、復元テストの有無です。バックアップファイルが壊れている、必要な世代が残っていない、復元手順を担当者が知らないといった問題は、障害が起きてから判明します。

### 4. 稼働・改ざん・期限の確認

サイトが表示できるか、SSL証明書やドメインの期限が近づいていないか、想定外のファイル変更がないかなどを確認します。ただし「監視」という言葉だけでは、確認間隔も通知条件も分かりません。何を、何分・何時間・何日ごとに見て、誰へ連絡するかを契約に書きます。

### 5. 問い合わせフォームの動作確認

トップページが表示されていても、フォームだけ送れないことがあります。保守対象に、送信テスト、通知メールの到達確認、自動返信、迷惑メール判定、保存先の確認が含まれるかを確かめます。フォームの停止は問い合わせ機会の損失につながるため、表示監視とは別に扱うべき項目です。

### 6. 月次報告と改善提案

作業報告には、実施した更新、バックアップ結果、検知した異常、次月までに判断が必要なことを含めます。アクセス数だけのレポートでは、保守作業の状況は分かりません。古い機能を残し続けるより再構築した方がよい場合に、判断材料を示してくれるかも比較点です。

## 契約前に確認する10項目

候補会社へ同じ質問を送り、回答を表にすると比較しやすくなります。

1. WordPress本体、テーマ、プラグイン、PHPのどこまでが更新対象か
2. 更新前にバックアップとテスト環境での確認を行うか
3. 更新後に確認するページと機能は何か
4. バックアップの対象、頻度、保存先、保存期間、復元テストの頻度
5. 稼働・改ざん・期限を何で、どの頻度で確認するか
6. 異常時の受付時間、一次回答の目安、連絡方法
7. 調査、隔離、駆除、復旧のどこまでが月額内か
8. 月額外になる作業と、その見積もり・承認方法
9. 再委託先やクラウドサービスを使う場合の管理方法
10. 解約時に返却されるデータ、アカウント、手順書は何か

回答が「状況に応じて対応」「必要に応じてバックアップ」のように曖昧な場合は、具体的な条件を追記してもらいます。すべてを月額内に入れる必要はありません。月額内と個別見積もりの境界が分かることが重要です。

## 見積もりを同じ条件で比べる

保守費用は、サイトの規模だけでなく、独自機能、更新頻度、監視間隔、緊急対応の条件で変わります。総額だけでなく、次の単位をそろえて比較してください。

| 比較項目 | 見積もりに書いてもらう内容 |
| --- | --- |
| 初期調査 | 現状確認、管理情報の整理、バックアップ取得、問題箇所の洗い出し |
| 月額保守 | 定期更新、確認頻度、報告、軽微修正の上限 |
| 個別作業 | PHP移行、プラグイン置換、機能改修、デザイン変更 |
| 緊急対応 | 受付条件、着手条件、調査・復旧の範囲、追加料金 |
| 契約終了 | データ返却、アカウント移管、引き継ぎ資料 |

一般的な費用構成は[ホームページ保守費用の相場](/blog/website-maintenance-cost-guide)で詳しく説明しています。自社のサイトに必要な作業を先に決めると、不要な項目を外し、必要な項目の抜けを防げます。

## 外注前に社内で用意する情報

保守会社へ渡す情報が散らばっていると、初期調査に時間がかかります。分かる範囲で構わないため、次を一覧にします。

- ドメインの管理会社、契約名義、更新日、ログイン方法
- サーバーの会社・プラン・契約名義・管理画面
- WordPress管理者、テーマ、主要プラグイン
- 制作データやソースコードの保存場所
- 問い合わせ通知先、メール、外部サービスとの連携
- Google Analytics、Search Console、タグ管理の権限
- 現在の制作会社・担当者・契約書・請求書
- 止まると事業に影響する機能と、社内の連絡先

ログイン情報を平文メールにまとめて送らず、権限を分けられるサービスでは作業用アカウントを発行します。契約終了時に無効化できる形にしておくと、委託先変更も安全に進められます。

## 選定から開始までの進め方

1. サイトと管理情報を棚卸しする
2. 必要な保守項目と、社内に残す作業を決める
3. 同じ依頼書を2〜3社へ送り、対象範囲をそろえて見積もる
4. テスト環境、バックアップ、緊急時、解約時の条件を確認する
5. 初期調査で見つかった問題を、保守開始前に直すか個別計画にする
6. 連絡先、承認者、定例報告、アカウント管理を決めて運用を始める

今のサイトが古く、更新だけでは維持しにくい場合は、保守契約を先に結ぶより再構築した方が負担を減らせることがあります。[WordPressは改修か再構築か](/blog/wordpress-repair-or-rebuild)の判断表も使ってください。

## よくある質問

### WordPressの更新だけを依頼できますか？

依頼できる会社はあります。ただし、バックアップ、互換性確認、更新後テスト、切り戻しを含むかを確認してください。管理画面で更新ボタンを押すだけの契約では、不具合時の対応が別料金になることがあります。

### サーバー会社の保守があれば十分ですか？

サーバー会社はサーバー基盤を管理しますが、WordPressのテーマ、プラグイン、独自機能まで管理するとは限りません。契約中のプランでどこまでが対象かを確認し、対象外を自社か保守会社で補います。

### 緊急時だけ依頼できますか？

単発で対応する会社もありますが、所有権やバックアップの確認から始まるため、すぐに復旧できるとは限りません。平常時から管理情報と戻し方を整え、緊急対応の受付条件を保守契約で決めておく方が現実的です。

### 契約期間はどのくらいがよいですか？

最低契約期間より、解約通知の期限、データ返却、アカウント移管、未完了作業の扱いを確認してください。最初の3か月程度で報告内容と対応品質を評価できる契約設計だと見直しやすくなります。

