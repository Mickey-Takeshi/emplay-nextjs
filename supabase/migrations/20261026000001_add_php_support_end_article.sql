## PHPとは：多くのホームページを裏側で動かす言語

PHPは、サーバーの上でホームページの中身を組み立てるプログラミング言語です。閲覧者がページを開くと、サーバーでPHPが動き、記事やお問い合わせフォームなどを表示します。閲覧者の画面にPHPが見えることはありません。

利用の広さは、ほかの言語を大きく引き離しています。調査会社W3Techsによると、サーバー側の言語が判別できたサイトのうち69.2%がPHPを使っています（2026年10月26日時点）。WordPressで作られたサイトだけでも、同社が調べたサイト全体の39.6%に上ります。WordPressのほか、EC-CUBEやDrupalなどもPHPで動いています。

土台が共通であるため、PHP本体に欠陥が見つかると、その上で動く多くのサイトがまとめて影響を受けます。WordPressの本体やプラグインを最新にしていても、土台のPHPが古ければ守れません。

## 脆弱性とは：攻撃に悪用されうるプログラムの欠陥

脆弱性は、プログラムの欠陥のうち、攻撃に悪用されうるものを指します。脆弱性が見つかると、開発元は欠陥を直した修正版を公開し、利用者がそれを適用することで守られます。ニュースや注意喚起には専門用語が多く出てくるため、知っておきたいものを整理します。

| 用語 | 意味 |
| --- | --- |
| CVE | 脆弱性ごとに付く、世界共通の識別番号 |
| CVSS | 深刻度を0〜10で表す指標。9.0以上は最も高い「Critical」 |
| リモートコード実行 | 外部から、サーバー上で任意のプログラムを動かされること |
| 修正版（パッチ） | 欠陥を直した版。適用して初めて守られる |
| サポート終了（EOL） | 開発元が修正版を出さなくなること |

なかでも危険度が高いのは、認証なしに外部から実行できるリモートコード実行です。サイトの改ざん、顧客情報の持ち出し、ほかのサイトへの攻撃の踏み台などに使われるおそれがあります。

## PHP2Shellとは：2つの重大な脆弱性の通称

PHP2Shellは、2026年10月21日にPHP公式が修正した2つの脆弱性の通称です。どちらも、認証なしに外部からサーバー上でプログラムを実行されるおそれがあります。IPAの注意喚起でも、識別番号とあわせてこの通称が使われています。

| 項目 | CVE-2026-109618 | CVE-2026-109619 |
| --- | --- | --- |
| 欠陥の場所 | メモリが足りなくなったときの処理 | 使い終わった内部の情報の扱い |
| 深刻度（CVSS v4.0） | 9.2 | 9.2 |
| 起きうること | リモートコード実行 | リモートコード実行 |

PHP公式によると、対象はWebのリクエストを処理するすべてのPHPです。なかでもApacheに組み込んで動かす方式（mod_php）は、サイトのプログラムが動く前に攻撃が成立しうるため、最も危険だとしています。研究者は、WordPress、Drupal、Joomla、Magentoなど、多くのアプリで再現できたと報告しています。

深刻度の評価は、機関によって分かれています。PHP公式の評価（CVSS v4.0）は2件とも「攻撃条件の複雑さ」を「高」としていますが、米国の脆弱性データベースNVDは独自の評価（CVSS v3.1）で、CVE-2026-109618の攻撃条件の複雑さを「低」、深刻度を9.8としています。公表の前に情報が出回り、悪用の試みも観測されているため、早めの更新が欠かせません。

## 影響範囲：どのPHPが対象か

修正版が出たのは、サポートが続いている8.2〜8.5だけです。それより古い版も影響を受けるとされていますが、正式な修正版は出ていません。どの版を使っているかで取るべき対応が変わるため、まずは自社サイトのPHPの版を把握することが出発点です。

| PHPの版 | 対象の範囲 | 公式の修正 |
| --- | --- | --- |
| 8.5 | 8.5.12より前 | 8.5.12 |
| 8.4 | 8.4.27より前 | 8.4.27 |
| 8.3 | 8.3.36より前 | 8.3.36 |
| 8.2 | 8.2.35より前 | 8.2.35 |
| 7.4・8.0・8.1 | 影響あり | 修正版は出ず、最小限の修正コードのみ |
| 5.4〜7.3 | 影響あり（研究者による） | 公式の修正は無い |

5.4〜7.3の「影響あり」は、発見者のWizなどの研究者の分析によるもので、IPAもこの分析を引用しています。

公式の修正が出ない古い版でも、レンタルサーバー会社などが独自に修正を作って当てている例があります。ただし応急的な対策で、版の番号だけでは修正の有無を判断できない場合もあります。具体的な確かめ方は、[自社サイトの確認方法と委託先への連絡文例](/blog/php-vulnerability-response)をご覧ください。

## なぜここまで大きな騒ぎになったのか

PHPの脆弱性はこれまでも見つかってきましたが、今回は国家サイバー統括室や首相が対応を呼びかける異例の事態になりました。背景には、利用の広さ、公表前の情報の漏えい、古いPHPの多さという3つの理由があります。

1. **利用が広い**：前述のとおり、サーバー側の言語が判別できたサイトの約7割がPHPを使っています。発見者のWizも、世界のサイトの約7割に影響しうるとしています。
2. **公表前に情報が出回った**：PHP財団によると、公表の前日に脆弱性の番号などが出回ったため、PHPは公表を1日早めました。発見した企業の一つが誤って公開した動画で、限られた詳細も広まりました。悪用の試みは、AmazonやCloudflareなど複数の企業が観測しています。一方、米国CISAは10月21日の時点で悪用は観測していないとしており、悪用が確認された脆弱性のカタログにも10月26日時点で載っていません。
3. **古いPHPが多く残っている**：W3Techsの版別の割合から計算すると、PHPを使うサイトの約半数が、正式な修正版の出ない8.1以前で動いています。IPAも、サポートが終わった古いPHPを使い続けるサイトが見受けられると指摘しています。

こうした事情から、国内では修正の適用までの間、予防のためにサービスを一時停止する企業も相次ぎました。サーバー会社でも、エックスサーバーが自社の公式サイトと管理画面を、ロリポップが一部のサーバーで利用者のサイトの表示を、一時的に止めました。

## 古いPHPが危険な理由：サポート期限の仕組み

2024年に決まった今の方針では、8.2以降の各版は、公開から2年間の通常サポートと、その後2年間のセキュリティ修正だけのサポートを受けられ、終了日は年末の12月31日にそろえられています。8.1も期限が1年延びて2025年末までとなりました。それより前に期限を迎えた8.0と7.4は、終了日が年末ではありません。期限を過ぎた版には、原則として修正版が出ません。

| PHPの版 | セキュリティサポートの終了日 |
| --- | --- |
| 7.4 | 2022年11月28日（終了） |
| 8.0 | 2023年11月26日（終了） |
| 8.1 | 2025年12月31日（終了） |
| 8.2 | 2026年12月31日 |
| 8.3 | 2027年12月31日 |
| 8.4 | 2028年12月31日 |
| 8.5 | 2029年12月31日 |

今回、修正版が8.2以降にしか出なかったのはこのためです。8.2のサポートも2026年12月31日で終わるため、8.2には、原則として2027年以降に見つかる脆弱性の修正版が出ません。

WordPressは、PHP 8.3以上を推奨しています。WordPress.orgが公開している統計から計算しても、WordPressサイトの約3分の1が8.1以前で動いています。古い版のまま使い続けると、次に重大な脆弱性が見つかったとき、更新という確実な対策がとれません。

IPAも10月22日の注意喚起で、更新・移行と、その後の維持管理に必要な人員・予算・保守体制を確保できるかを経営層も含めて検討し、難しければ移行や公開の終了も検討するよう求めています。移行の判断と手順は、[PHP 8.2のサポート終了は2026年12月31日｜WordPressサイトの移行判断](/blog/php-support-end-migration)で解説しています。

## 過去にもあったPHPの重大な脆弱性

PHP本体の重大な脆弱性は、今回が初めてではありません。いずれも外部からプログラムを実行されるおそれがある重大なもので、修正版への更新が対策でした。日本の公的機関が注意喚起した主な例を挙げます。

| 時期 | 脆弱性 | 内容と公的機関の対応 |
| --- | --- | --- |
| 2012年5月 | CVE-2012-1823 | CGIとして動かすPHPで、外部からプログラムを実行されるおそれ。JPCERT/CCが注意喚起 |
| 2024年6月 | CVE-2024-4577 | 特定の言語設定（日本語など）のWindows上でCGIとして動かすPHPで、外部からプログラムを実行されるおそれ。IPAは国内での被害を確認したとして注意喚起（2024年7月） |

CVE-2024-4577は、公表から数日で、米国CISAの「悪用が確認された脆弱性」のカタログに登録されました。重大な脆弱性は今後も見つかると考えられるため、「いつか起きる」前提で、すぐに更新できる体制を持っておくことが大切です。

