## ChatGPT広告とは

ChatGPT広告とは、利用者とChatGPTの会話内容に関連する商品やサービスを、ChatGPTの回答とは別の広告枠に表示する仕組みです。OpenAIの説明では、広告は回答の下に表示されることがあり、広告主名、ファビコン、タイトル、説明文、ランディングページ、画像で構成されます。

重要なのは、広告が回答本文の一部ではないことです。OpenAIは広告を明確にラベル表示し、ChatGPTの回答から分離すると説明しています。広告費を払っても、回答の内容やおすすめ順位を買うことはできません。AIO・LLMOで回答内の引用や言及を目指す施策と、ChatGPT広告で広告枠を購入する施策は分けて考える必要があります。

[OpenAIの提供地域に関する発表](https://openai.com/index/testing-ads-in-chatgpt/)によると、2026年2月に米国で広告テストが始まり、同年8月11日の更新で日本を含む複数市場での提供開始が案内されました。さらに、[Ads Managerの提供状況](https://help.openai.com/en/articles/20001245-ads-manager-availability)では、日本に所在し、請求を受ける法人によるセルフサービスが「Available」とされています。提供状況は変わる可能性があるため、実際に出稿する時点で公式ページを確認してください。

広告が表示される利用者にも条件があります。[Ads in ChatGPT](https://help.openai.com/en/articles/20001047)によると、広告はFreeおよびGoプランの利用者に表示される場合があり、Plus、Pro、Business、Enterprise、Eduの利用者と、18歳未満と判定されたアカウントには表示されません。自社の見込み顧客がどのプランを使っていそうかは、媒体を選ぶ際の判断材料になります。

## Google検索広告やSNS広告との違い

ChatGPT広告の最大の違いは、短い検索語だけでなく、会話の流れを広告配信の関連性判断に使う点です。利用者はChatGPTに、目的、条件、迷っている点を文章で伝えることがあります。その文脈に合う広告を出せれば、比較や意思決定の途中に接点を持てます。

一方で、検索広告の完全一致キーワードのように「この言葉が入力されたら必ず配信する」という指定はできません。広告グループに設定するコンテキストヒントは、商品が役立つ会話や利用場面をOpenAIのシステムへ伝える補助情報であり、配信対象を固定するルールではありません。

| 比較軸 | ChatGPT広告 | Google検索広告 | Meta広告 |
|---|---|---|---|
| 主な接点 | 会話しながら比較・検討している場面 | 検索語を入力した場面 | フィードや動画を閲覧している場面 |
| 関連性の主な手掛かり | 会話の文脈、意図、広告内容、コンテキストヒント | キーワード、検索意図、広告・LP | 属性、行動、興味関心、クリエイティブ |
| 向きやすい目的 | 比較検討中の認知、サイト訪問、獲得 | 顕在需要の獲得 | 認知、需要喚起、リターゲティング |
| 運用上の特徴 | 会話の利用場面ごとに広告グループを分ける | 検索語句とキーワードを精査する | オーディエンスと画像・動画を検証する |

この表は、優劣ではなく役割の違いを示しています。すでに検索広告で顕在層を獲得できている会社なら、ChatGPT広告で比較検討中の接点を増やす意味があります。逆に、ランディングページやコンバージョン計測が整っていない状態では、新しい媒体を増やすより先に受け皿を直すほうが成果につながります。広告媒体全体の使い分けは、[Web広告の種類と選び方](/blog/web-ads-types-comparison)も参照してください。

## ChatGPT広告の表示形式と配信の仕組み

広告はChatGPTの回答下に表示されることがあり、通常は次の要素を含みます。

- 広告主名
- ファビコンまたはロゴ
- タイトル
- 説明文
- ランディングページへのリンク
- 正方形の画像

[ChatGPT広告の基本](https://help.openai.com/en/articles/20001207-ads-in-chatgpt-the-basics)によると、広告の選定には現在の会話の文脈や意図、広告のタイトル・説明文・ランディングページ、広告主が設定したコンテキストヒントなどが使われます。広告パーソナライズが有効な場合は、利用者のChatGPT利用に関する一部のシグナルも考慮されることがあります。

広告グループは、商品名ではなく「どのような状況で役立つか」まで含めて分けると設計しやすくなります。例えば会計ソフトなら、「初めて法人決算を準備する小規模事業者」と「請求書処理を自動化したい経理部門」は、同じ製品でも悩みと訴求が異なります。広告グループ、コンテキストヒント、広告文、ランディングページをそれぞれの利用場面にそろえます。

コンテキストヒントには、実在する用途と利用者の課題を具体的に書きます。「経営に関心がある人」のように広げすぎると、広告文と会話の関連性が弱くなります。一方、「会計ソフト おすすめ」という単語だけでは、キーワード広告の設計から抜け出せません。[広告グループの公式ガイド](https://help.openai.com/en/articles/20001211-create-ad-groups-for-chatgpt-ads)でも、1つの広告グループを共通の商品カテゴリ、テーマ、意図に集中させ、異なる利用者や用途は分けるよう案内されています。

## ChatGPT広告の料金方式と費用の内訳

ChatGPT広告には、目的に応じてCPM、CPC、コンバージョン最適化型CPCの選択肢があります。固定の掲載料金を払うのではなく、キャンペーン目的と入札を設定し、広告オークションを通じて配信される仕組みです。

| 目的 | 課金の考え方 | 向いている施策 |
|---|---|---|
| CPM | 1,000回の表示に対して課金 | 新商品やブランドの認知拡大 |
| CPC | 有効なクリックに対して課金 | サイト訪問や比較ページへの送客 |
| oCPC | クリック課金のまま、指定したCVへ配信を最適化 | 購入、問い合わせ、登録などの獲得 |

oCPCでも「コンバージョン1件ごとの課金」になるわけではなく、有効なクリックに対して費用が発生します。また、既存のCPM・CPCキャンペーンを後からoCPCへ変更するのではなく、新しいキャンペーンとして作成する必要があります。

[キャンペーン作成の公式ガイド](https://help.openai.com/en/articles/20001210-create-campaig)では、日本の最低日予算は2,500円と案内されています。ただし、最低額は成果が出る予算を意味しません。実際に必要な予算は、クリック単価、必要なデータ量、目標CPA、検証する広告グループ数で変わります。

「ChatGPT広告にいくら必要か」を考えるときは、OpenAIへ支払う広告費と、運用を外部へ依頼する場合の支援費を分けます。主な費用は次のとおりです。

| 費用 | 内容 | 金額の考え方 |
|---|---|---|
| 広告費 | OpenAI Ads Managerで消化する媒体費 | 日本の最低日予算は2,500円。実際のテスト予算は目的と必要なデータ量から決める |
| 初期設定費 | アカウント、計測、キャンペーンの初期構築 | アカウント状況、OpenAI Pixel、Conversions APIなどの実装範囲で変わる |
| 運用代行費 | 入札・予算調整、広告改善、分析、報告 | 月額固定または広告費に対する料率など、依頼先の料金体系で変わる |
| 制作・開発費 | 広告画像、ランディングページ、計測開発 | 必要な制作物と実装内容に応じて別途発生する場合がある |

最低日予算だけを見て総額を判断すると、計測や制作に必要な費用が抜けます。見積りを比較するときは、広告費、初期設定、月次運用、画像制作、ランディングページ、計測実装のうち、どこまで含まれるかを確認してください。EMPLAYへ運用を依頼する場合も、商材、予算、ランディングページ、計測環境を確認したうえで支援範囲と費用を個別にご案内します。

初回は「最低額だから2,500円」と決めるのではなく、次の式からテスト予算を考えます。

```text
テスト予算 = 想定CPC × 確保したいクリック数
```

想定CPCがまだ分からなければ、少額で配信し、実際の平均CPCとコンバージョン率を確認してから増額します。Google広告やMeta広告と同じ予算を最初から移すのではなく、新規媒体の検証枠として切り出す方法が安全です。予算設計の基本は[Web広告の予算の決め方](/blog/web-ads-budget-planning)で解説しています。

## 日本からChatGPT広告を出稿する手順

出稿作業は、アカウント、キャンペーン、広告グループ、広告、計測の順に進めます。広告文から作り始めると、目的や計測が後回しになり、配信後に良し悪しを判断できません。

### 1. Ads Managerの広告主アカウントを準備する

[Ads Manager Betaのアカウント設定](https://help.openai.com/ja-jp/articles/20001213)では、OpenAIアカウントを使ってAds Managerへ登録し、事業者情報、国、通貨、タイムゾーンなどを入力した後、アカウント認証、請求設定を完了する流れが案内されています。事業者名、Webサイト、ロゴ、業種、請求先情報を先にそろえておきます。

国、通貨、タイムゾーンは後から変更できないため、広告を掲載し、請求を受ける法人の情報で登録してください。運用代行会社が支援する場合も、広告主ごとに専用アカウントを作り、広告主側が所有権を保持する設計が引き継ぎやすくなります。

### 2. 目的とコンバージョンを決める

認知ならCPM、サイト訪問ならCPC、購入や問い合わせを増やすならoCPCが候補です。目的はキャンペーン作成後に変更できないため、「とりあえずクリック」で始めず、配信後に何を成果とみなすかを決めます。

問い合わせを目標にする場合は、フォーム送信完了だけでなく、有効問い合わせ数や商談数も社内で追います。広告管理画面のコンバージョンだけを増やしても、営業につながらなければ事業成果とはいえません。

### 3. 広告グループとコンテキストヒントを設計する

商品カテゴリ、対象者、利用場面が異なる場合は広告グループを分けます。コンテキストヒントには、商品が役立つ会話の状況を複数の表現で記述します。

例えば法人向けオンライン英会話なら、次のように利用場面を分けられます。

- 海外拠点との会議に備えたい管理職
- 英語での営業提案を練習したい担当者
- 海外赴任前に短期間で学びたい社員

これらを1つの広告グループへ詰め込むより、悩みごとに広告文とランディングページを変えたほうが、広告を見た人が自分向けだと判断しやすくなります。コンテキストヒントは配信保証ではないため、実際の表示回数と反応を見ながら範囲を調整します。

### 4. タイトル、説明文、画像を制作する

広告は、派手な言葉より「誰の、どの課題に、何が役立つか」が伝わることを優先します。[広告制作の公式ガイド](https://help.openai.com/en/articles/20001212-create-ads-and-creative-variations)では、明確で具体的な便益を示し、同じ訴求を繰り返すのではなく、異なる切り口の広告を複数用意するよう勧めています。

[キャンペーン公開の公式ガイド](https://help.openai.com/en/articles/20001209)に記載された一括アップロードの仕様では、タイトルは16〜24文字が推奨で最大50文字、説明文は32〜48文字が推奨で最大100文字、画像は公開URLで取得できる正方形のPNGまたはJPGで、1,200×1,200ピクセル以下と案内されています。管理画面の表示や仕様が変わる可能性があるため、制作前に最新の入力欄を確認してください。

広告とランディングページの約束も一致させます。「無料で試せる」と広告に書くなら、リンク先で対象条件と開始方法がすぐ分からなければなりません。トップページへ送るより、商品、料金、申込み方法がまとまった専用ページへ送るほうが判断しやすくなります。

また、ランディングページでOAI-AdsBotとOAI-SearchBotをブロックしていると、審査や広告作成に支障が出る可能性があります。robots.txt、CDN、WAFの設定も確認してください。

### 5. コンバージョン計測を設定する

クリックだけでなく購入や問い合わせまで判断するには、配信前に計測を用意します。[Conversion Measurement](https://help.openai.com/en/articles/20001409-conversion-measurement)では、OpenAI Pixel、Conversions API、または両方でイベントを送る方法が案内されています。

広告クリック時には`oppref`というクリック参照値がランディングページURLへ付与されます。リダイレクトやページ遷移の途中でこの値を失わないようにし、サーバーからイベントを送る場合は利用可能な`oppref`をConversions APIへ含めます。ブラウザとサーバーの両方から同じコンバージョンを送る場合は、同一のイベントIDで重複を除外します。

第三者のアクセス解析でも流入を確認できるよう、広告URLにはUTMパラメータを設定します。OpenAI Ads ManagerとGA4ではアトリビューション期間や集計方法が異なるため、コンバージョン数が完全一致しないことがあります。差が出たら、日付、タイムゾーン、重複除外、同意管理、イベント発火条件の順に確認します。

計測で個人情報を扱う場合は、利用者への説明と必要な同意を整えます。技術的に送信できる情報でも、プライバシーポリシーや適用法令に照らして送ってよいとは限りません。

### 6. 審査後に配信し、少額で検証する

アカウント認証、請求設定、広告審査が完了すると配信できます。審査中に開始日を決め打ちせず、管理画面のステータスを確認して公開スケジュールを組みます。

開始直後は広告グループを増やしすぎず、表示回数、クリック、費用、CTR、平均CPC、コンバージョンを確認します。最初から短期間のCPAだけで結論を出すのではなく、広告が表示されない、表示されるがクリックされない、クリックされるがコンバージョンしない、のどこに問題があるかを分けます。

## ChatGPT広告が向いている企業と向かないケース

ChatGPT広告は、利用者が比較や意思決定のために情報を整理する場面と相性があります。商品やサービスの用途を具体的に説明でき、比較検討に必要なランディングページを用意できる企業は検証しやすいでしょう。

向いている可能性があるケース:

- EC商品、旅行・体験、教育、デジタルサービスなど、利用場面を具体化しやすい
- 検討時に複数の条件や選択肢を比べる商材
- 広告ごとに関連する商品ページや比較ページへ誘導できる
- 問い合わせ、購入、登録などのコンバージョン計測ができる
- 新しい媒体を少額で検証し、結果に応じて改善できる

先に別の課題を直すべきケース:

- 商品の対象者と価値が明文化されていない
- 広告のリンク先がトップページしかない
- 問い合わせや購入の計測ができていない
- 広告審査で制限される業種・内容に該当する
- 1週間程度で確実な成果を求めている

OpenAIの[広告ポリシー](https://openai.com/policies/ad-policies/)では、広告可能なカテゴリと禁止・制限対象が定められています。政治、成人向け、ギャンブル、アルコール・たばこ、規制領域などには禁止や地域別の制限があり、広告だけでなく画像とランディングページも審査対象です。出稿準備の前に、自社の商品と訴求内容が対象になるかを確認してください。広告表現全体の法令確認は[広告表現の法規制と確認手順](/blog/ad-legal-compliance-guide)も参考にしてください。

## 配信後に見る指標と改善の順番

ChatGPT広告の改善は、指標を一度に眺めるのではなく、利用者が進む順番に確認します。

| 状況 | 主に確認するもの | 改善の方向 |
|---|---|---|
| 表示されない | 審査、入札、予算、広告グループの焦点、ポリシー | 配信資格と設計を確認する |
| 表示されるがクリックされない | タイトル、説明文、画像、会話文脈との関連性 | 利用場面ごとに訴求を作り分ける |
| クリックされるがCVしない | LPの内容、表示速度、広告との整合性、フォーム | 広告ではなく受け皿を改善する |
| CVはあるが商談・売上にならない | CV定義、対象者、営業連携、受注率 | 事業成果に近い指標へ見直す |

判断の順番は、配信資格、表示、クリック、コンバージョン、商談・売上です。上流の段階で問題があるときに、下流の指標だけを改善しようとしても原因は解消しません。

CTRが低いからタイトルだけを変える、と決めつけないことが大切です。広告グループが広すぎれば、どれだけコピーを直しても関係の薄い会話へ表示されます。逆にクリック後の離脱が多ければ、コンテキストヒントよりランディングページを直すべきです。

費用対効果は、媒体内のコンバージョンだけでなく、売上または粗利まで追って判断します。ROASとCPAの使い分け、数字が悪いときの切り分けは[ROASの計算方法と改善手順](/blog/roas-improvement-strategies)で確認できます。

## 自社運用と運用代行の選び方

