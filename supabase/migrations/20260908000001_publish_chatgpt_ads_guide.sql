## よくある質問

### ChatGPT広告は日本から出稿できますか？

はい。2026年9月8日時点で、日本に所在し、請求を受ける法人はAds Managerのセルフサービスを利用できます。ただし、アカウント作成後に認証と審査があり、広告対象の商品・サービスや表現によっては掲載できません。提供状況と広告ポリシーは出稿時に公式ページで再確認してください。

### ChatGPT広告はいくらから始められますか？

OpenAIの公式ガイドでは、日本の最低日予算は2,500円と案内されています。ただし、最低予算と成果を判断できる予算は異なります。想定CPC、必要なクリック数、目標CPA、検証する広告グループ数からテスト予算を決め、結果を見て増減します。運用代行を依頼する場合は、広告費とは別に初期設定費、運用代行費、画像やLPの制作費、計測実装費が必要になる場合があります。

### キーワードを指定して広告を出せますか？

検索広告の完全一致キーワードと同じ指定はできません。広告グループにコンテキストヒントを設定し、商品が役立つ会話、利用場面、課題を伝えます。ヒントに含めた言葉が入力されたときの配信や、特定の質問への表示を保証する機能ではありません。

### ChatGPT広告を出すと回答内で紹介されますか？

いいえ。OpenAIは広告とChatGPTの回答を分離しており、広告掲載が回答内容へ影響しないと説明しています。回答内での引用や言及を増やすSEO・AIO・LLMOと、有料広告枠へ表示するChatGPT広告は別の施策です。

### Google広告とChatGPT広告はどちらを優先すべきですか？

すでに検索している顕在層を獲得したい場合は、Google検索広告を先に検討しやすいでしょう。比較条件を整理している人との新しい接点を増やしたい場合は、ChatGPT広告をテストする意味があります。どちらか一方を感覚で選ばず、対象者、目的、ランディングページ、計測体制、予算から判断します。

### ChatGPT広告の成果はどのように測定しますか？

Ads Managerで表示回数、クリック、費用、CTR、平均CPC、平均CPM、コンバージョンを確認できます。コンバージョンはOpenAI PixelまたはConversions APIで計測し、UTMパラメータを使ってGA4などでも流入後の行動を確認します。管理画面ごとに集計方法が違うため、数値の完全一致ではなく差の理由を説明できる状態を目指します。

