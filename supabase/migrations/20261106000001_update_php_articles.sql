## よくある質問

### PHP2Shellとは何ですか？

2026年10月21日にPHP公式が修正した、2つの重大な脆弱性（CVE-2026-109618とCVE-2026-109619）の通称です。認証なしに外部からサーバー上でプログラムを実行されるおそれがあり、深刻度はCVSS v4.0で9.2です。

### PHPを使っていないサイトも影響を受けますか？

今回の脆弱性はPHP本体のものなので、PHPを使っていないサイトは対象外です。ただし、HTMLだけのサイトでも、お問い合わせフォームなどにPHPを使っていることがあります。分からない場合は、制作会社やサーバー会社に確かめてください。

### なぜPHP 8.1以前には修正版が出ないのですか？

開発元のサポート期間が終わっているためです。PHP公式は7.4・8.0・8.1向けに最小限の修正コードを公開しましたが、正式な修正版は出していません。サーバー会社やOSの提供元が独自に修正を出す場合もありますが、根本的な対策はサポート中の版へ移ることです。

### WordPressを最新にしていれば安全ですか？

いいえ。WordPress.orgも、今回はWordPress固有の問題ではなく本体の更新は不要としたうえで、サーバーのPHPの版を確かめるよう案内しています。WordPressとPHPの両方を最新に保つ必要があります。

### PHPは危険な言語なのですか？

言語そのものが特に危険というわけではありません。広く使われるソフトウェアには、どれも脆弱性が見つかります。大切なのは、修正版が出たときにすぐ更新できる体制と、サポートが続く版を使うことです。

