> 2. 今回の脆弱性への対応状況（修正版への更新、またはサーバー会社による修正の適用。完了した日時と、更新後にPHPを再起動して反映を確かめたかも）
> 3. 対応後に、お問い合わせフォームや決済などの動作を確認したか
> 4. PHP 8.1以前の場合、サポート中の版へ移行する見通し
