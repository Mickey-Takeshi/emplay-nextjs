>
> お手数ですが、〇月〇日までにご回答いただけますと幸いです。

### 回答の読み方

| 回答 | 読み方と次の行動 |
| --- | --- |
| 修正版（8.5.12／8.4.27／8.3.36／8.2.35）以降に更新し、PHPを再起動して反映を確かめた | 対応済み。動作確認と、不審なアクセスや改ざんの形跡の確認結果もあわせて聞く |
| サーバー会社が修正を適用した（番号は変わらない） | 共用のレンタルサーバーでは起こりうる。サーバー会社の告知で確かめる |
| 8.1以前だが、サーバー会社の応急の修正が入った | 今回はしのげても、次の脆弱性には修正が出ないおそれがある。移行を計画する |
| 確認中・分からない | 回答の期限を決めて再確認する。VPSや自社のサーバーなら至急 |
| 返事が無い・保守契約が無い | サーバー会社に契約者として直接問い合わせ、管理を任せる先を探す |

※PHP公式は10月23日、修正版でも、設定とアプリのプログラムがまれな組み合わせのときにだけ残る攻撃の経路があるとして、次の通常の更新まで一部の機能（session.upload_progress）を無効にするよう勧めました。VPSなどでPHPの設定を自社か委託先が管理している場合は、この設定の扱いもあわせて確かめてください。共用のレンタルサーバーでは、サーバー会社の告知に従います。

保守契約の範囲外として、費用を求められることもあります。今回の対応がどこまで契約に含まれるのかを今確かめておくと、次の脆弱性のときに慌てずに済みます。

なお、今すぐのPHPの更新は、サーバー会社の管理画面や、現在の委託先で進めるのが最も早い方法です。そのうえで、委託先と連絡が取れない、保守を任せる先が無い、PHPを上げたら表示や機能が崩れたといった場合は、EMPLAYに[お問い合わせ](/contact)ください。サイトの状況を伺い、修正や移行、保守の進め方をご提案します。

## PHP 8.1以前のサイトはどうするか

PHP 8.1以前は、開発元のサポートがすでに終わっています。今回もPHP公式から修正版は出ず、7.4・8.0・8.1向けに最小限の修正コードが示されただけで、それより古い版には何も出ていません。

サーバー会社が独自に修正を当てた例もありますが、ロリポップはこれを応急的な対策とし、今後の脆弱性には対応できない可能性があると説明しています。IPAも、サポートが続いている版や移行先の製品・サービスに移るよう求めています。

移る先の版にも期限があります。PHPの各版のセキュリティサポートの終了日は次のとおりです。

| PHPの版 | セキュリティサポートの終了日 |
| --- | --- |
| 8.1以前 | 終了済み |
| 8.2 | 2026年12月31日 |
| 8.3 | 2027年12月31日 |
| 8.4 | 2028年12月31日 |
| 8.5 | 2029年12月31日 |

8.2も2026年12月31日で終わるため、移るなら8.3以降が現実的です（テーマやプラグインの対応が前提）。移行の方法は、サイトの状態で3つに分かれます。

| 方法 | 向いているサイト | 注意点 |
| --- | --- | --- |
| PHPの版を上げる | WordPress本体・テーマ・プラグインが新しい版に対応している | バックアップを取り、検証用の環境で試してから切り替える |
| 直してから上げる | 独自のプログラムや古いプラグインの一部が動かない | 動かない部分の洗い出しと修正に時間がかかる |
| 作り直す | 長く更新されていないテーマ・プラグインが多い。デザインや内容も古い | 費用と期間はかかるが、保守しやすい形に整えられる |

判断の目安は、テーマとプラグインの更新が続いているかどうかです。何年も更新されていないものが多ければ、PHPの版だけを上げても、次の不具合や脆弱性につながりやすくなります。作り直すかどうかは、[ホームページが古いままだとどうなる？リニューアル判断チェック](/blog/outdated-website-risks)も参考にしてください。

期限までの移行の判断と手順は、[PHP 8.2のサポート終了は2026年12月31日｜WordPressサイトの移行判断](/blog/php-support-end-migration)で詳しく解説しています。

古いPHPからの移行や作り直しは、EMPLAYの[ホームページ制作サービス](/service/hp)でもご相談いただけます。

## ECサイト・会員サイトが特に確かめること

顧客の個人情報や注文の情報を扱うサイトは、被害が起きたときの影響が大きくなります。修正の適用に加えて、次の点も確かめてください。

EC-CUBEの開発元も10月22日に、至急の対応を求める案内を出しました。サーバーを自社や委託先で管理している場合は、修正版の適用と、反映の確認を求めています。EC-CUBE本体やプラグインを更新しても、サーバー側のPHPは修正されない点にも注意が必要です。PHPを更新する際は、購入や決済などの主な機能が動くかの確認も欠かせません。

- **侵害の形跡が無いか**：身に覚えのない管理者アカウントやファイル、ページの書き換え、別のサイトへの転送、サーバー会社やGoogleからの警告が無いかを、委託先に確かめてもらう。形跡があっても、調査に必要な記録が消えるため、慌ててデータを消さない
- **形跡があったときの相談先**：サーバー会社と委託先に加えて、セキュリティの専門会社に調査を依頼する。IPAの「情報セキュリティ安心相談窓口」でも相談を受け付けている
- **個人情報の漏えいのおそれ**：不正アクセスによる漏えいのおそれがある場合、人数にかかわらず、個人情報保護委員会への報告と、原則として本人への通知が必要になる。詳しくは[個人情報保護法対応ガイド](/blog/personal-data-protection-guide)を参照
- **カード決済**：決済を外部の決済代行会社に任せていても、入力画面が改ざんされればカード情報が盗まれるおそれがある。不審な点があれば決済代行会社にも連絡する

## 便乗詐欺に注意する

大きな脆弱性が報じられると、それに便乗した詐欺も出てきます。SNSでは、PHPの対策を口実にログインを促すメールが届いたという投稿も見られます。サーバーや管理画面のログイン情報が盗まれると、脆弱性とは別の経路でサイトを乗っ取られるおそれがあります。

- サーバー会社や制作会社を名乗り、「至急ログインして対策を」と促すメールやSMSは、リンクを開かずに公式サイトから確かめる
- 突然届く「無料で脆弱性を診断します」「今すぐ対策しないとサイトが止まる」といった連絡には、すぐに応じず、契約中の会社に確かめてから判断する
- 管理画面のIDやパスワードを、電話やメールで聞かれても答えない

手口と社内での防ぎ方は、[フィッシング詐欺対策ガイド](/blog/phishing-prevention-guide)で詳しく解説しています。

