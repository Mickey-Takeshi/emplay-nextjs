## PHP 8.2のサポートはいつまで？各版の期限

PHPの各版には、決まったサポート期限があります。今の方針では、公開から2年間の通常サポートと、その後2年間のセキュリティ修正だけのサポートを受けられ、終了日は年末の12月31日にそろえられています。8.2は2022年12月に公開された版で、2026年12月31日にセキュリティ修正のサポートも終わります。

| PHPの版 | セキュリティサポートの終了日 | 移行の目安 |
| --- | --- | --- |
| 8.1以前 | 終了済み（8.1は2025年12月31日） | 年内を待たず、サポート中の版へ移る |
| 8.2 | 2026年12月31日 | 年内に8.3以降へ移る計画を立てる |
| 8.3 | 2027年12月31日 | 移行先の候補。WordPressの推奨（8.3以上）を満たす |
| 8.4 | 2028年12月31日 | 移行先の候補。WordPress 6.7以降が対応 |
| 8.5 | 2029年12月31日 | 最新の版。WordPress 6.9以降が対応 |

表のWordPressの版は、本体が正式に対応する版です（WordPressの互換表、2026年8月19日更新。8.3は6.4以降）。テーマやプラグインの対応は、これとは別に確かめます。

期限が決まっている仕組みや、古い版が危険な理由は[PHPの脆弱性とは？](/blog/php-vulnerability-explained)で詳しく解説しています。この記事では、期限までに何を決め、どう移るかに絞って説明します。

## サポートが終わると何が起きるか

期限を過ぎても、サイトがすぐに表示されなくなるわけではありません。ただし、その後に見つかった脆弱性には、原則として公式の修正版が出なくなります。重大な脆弱性が見つかっても、更新という基本の対策をとれない状態が続きます。今回のPHP2Shellでも、サポート中の版と終わった版とで、受けられる対応に大きな差が出ました。

### PHP2Shellで起きたこと

PHP公式が修正版を出したのは8.2〜8.5だけで、サポートが終わった7.4・8.0・8.1には、最小限のソースコードの修正が示されたのみでした。レンタルサーバー会社の中には、古い版にも独自に修正を当てたところがあります。そのうちのロリポップは、8.1以下について「今回の対策は応急的なもの」とし、利用者にPHP 8.2以降への切り替えを求めています。

### 公的機関が求めていること

IPAも10月22日の注意喚起で、修正の出ない版を使っている場合は、サポート中の版への更新や、対策済みの製品・サービスへの移行を検討するよう求めました。経営層も含めて、更新・移行と、その後の維持管理に必要な人員・予算・保守体制を確保できるかを検討し、見通しが立たなければ、機能の縮小や公開の終了も含めて検討するよう呼びかけています。

## 自社サイトは移行が必要か：今の版で判断する

まず、自社サイトがどの版のPHPで動いているかを確かめます。WordPressなら、管理画面の「ツール」→「サイトヘルス」→「情報」→「サーバー」でPHPの版を確認できます。サーバー会社が修正だけを取り込んだ場合は末尾の番号が変わらないことがありますが、サポート期限は「8.2」「8.3」といった最初の2つの数字で判断します。制作会社や保守会社に管理を任せている場合は、版とあわせて、移行の予定があるかを聞いてください。

| 今のPHPの版 | 状況 | やること |
| --- | --- | --- |
| 8.1以前 | すでにサポートが終わっている | 年内を待たず、サポート中の版への移行を急ぐ |
| 8.2 | 12月31日でサポートが終わる | 年内に8.3以降へ移る計画を立てる |
| 8.3以降 | サポート中 | 期限を把握し、次の移行の時期を決めておく |

WordPressは、PHP 8.3以上を推奨しており、それより古い版で動くサイトにはPHPの更新が欠かせないとしています。WordPress.orgが公開している統計から計算すると、WordPressサイトの約3分の1がまだ8.1以前で動いており、8.2で動くサイトも2割強あります。8.3以上で動くサイトは約4割です（2026年10月26日時点）。

WordPress以外でも、ECサイトの構築ソフトや、独自に開発した予約・会員の仕組みなど、PHPで動いているものがあります。こうした仕組みは、ソフトの提供元や開発した会社に、新しい版への対応状況と移行の予定を確かめてください。

## 版を上げるか、直すか、作り直すか

移行の方法は、サイトの状態で大きく3つに分かれます。判断の目安は、WordPress本体・テーマ・プラグインの更新が続いているかどうかと、独自に作り込んだ機能がどれだけあるかです。どれに当たるか迷うときは、テスト環境で新しい版に切り替えてみて、何が動かないかを洗い出すのが確実です。

### 版を上げるだけで済む場合

WordPress本体を最新にでき、使っているテーマとプラグインがどれも更新され続けているなら、PHPの版を上げるだけで済む可能性が高いです。作業の中心は、テスト環境での確認と本番の切り替えになります。

### 直してから上げる場合

独自に作った機能や、更新が止まったプラグインの一部が新しい版で動かない場合は、その部分を直してから版を上げます。PHP公式は、版ごとに動かなくなる書き方や使えなくなる機能を「下位互換性のない変更点」として移行ガイドで公開しており、古いコードほど直す箇所が増えがちです。8.1から8.3へのように版を飛ばして上げる場合は、途中の版の変更点もあわせて確かめます。

### 作り直しを考える場合

何年も更新されていないテーマやプラグインが多く、WordPress本体も古い版のままといったサイトは、版を上げても次の不具合や脆弱性への対応が続きます。デザインや掲載内容も古くなっているなら、作り直して保守しやすい形に整えた方が、長い目で見て負担が小さくなることがあります。

作り直す場合も、新しいサイトを公開するまでは、今のサイトを動かし続けることになります。その間に今のサイトをどう守るか（PHPの版だけでも先に上げられないか、使っていない機能を止められないか）も、あわせて決めておきます。

## PHPの版を上げる手順

版の切り替えは、管理画面から操作できるレンタルサーバーが多い一方、確認を飛ばすと表示の崩れやフォームの不具合につながります。特に、問い合わせフォームや決済が止まっても、すぐには気づきにくいものです。委託先に任せる場合も、この流れに沿って進めてもらえるかを確かめておくと安心です。次の順番で進めます。

1. **バックアップを取る**：ファイルとデータベースの両方を保存し、戻し方も確かめておく
2. **テスト環境を用意する**：本番と同じ内容の検証用サイト（ステージング）を作る
3. **WordPress本体・テーマ・プラグインを更新する**：新しい版に対応した版にそろえる
4. **テスト環境で新しい版に切り替え、主要な機能を確かめる**：表示、問い合わせフォーム、会員ログイン、決済、管理画面の操作
5. **本番を切り替える**：本番も更新をそろえたうえで、アクセスの少ない時間帯に行い、すぐに同じ確認をする
6. **問題があれば元の版に戻す**：レンタルサーバーなら、管理画面で元の版を選び直す

WordPress.orgの案内も、版を上げること自体は通常は問題にならないはずだとしながら、問題が起きないとは保証できないとして、先にバックアップを取り、WordPress本体・テーマ・プラグインを更新しておくよう勧めています。主なレンタルサーバー会社は、PHPの版を切り替える手順を公式のマニュアルで公開しています。共用のレンタルサーバーでは、サーバー会社が行うのはPHP本体の提供と修正までで、サイトが新しい版で正しく動くかの確認は、利用者か委託先の仕事です。VPSや自社で管理するサーバーでは、PHP本体の更新も利用者側の作業です。

## 年内に終えるための進め方

12月は年末年始の休業も重なり、作業に使える日は思ったより少なくなります。問題が見つかったときに直す時間や、社内で表示や機能を確かめる時間も見込んで、期限から逆算して動き始めるのが安全です。11月の初めに動き始める場合の進め方の一例は、次のとおりです。

| 時期 | やること |
| --- | --- |
| 11月前半 | 今のPHPの版を確かめ、委託先かサーバー会社に移行の相談をする |
| 11月中 | テスト環境で新しい版に切り替え、動かない部分を洗い出して直す |
| 12月前半 | 本番を切り替え、表示・フォーム・決済などを確かめる |
| 12月後半 | 予備の期間。問題が出たときの修正や、元の版に戻す判断にあてる |

11月の後半以降に始める場合も、考え方は同じです。テスト環境での確認を省かず、本番の切り替えを12月の前半までに終える目安で、日程を組み直します。作り直しを選ぶ場合は、年内に公開まで終えるのは難しいことが多いため、新しいサイトの公開時期と、それまでの今のサイトの守り方を早めに決めておきます。

## 委託先・サーバー会社に確かめること

制作会社や保守会社にサイトを任せている場合は、次の点を文書で確かめておくと、移行の段取りと費用の見通しが立ちます。口頭の「大丈夫です」だけで済ませず、移行先の版と時期、確認の範囲を書面やメールで残しておくと、あとで食い違いが起きにくくなります。

- 今のPHPの版と、移行先の版・時期
- テスト環境で確かめてから本番を切り替えるか
- 動かないテーマ・プラグイン・独自の機能があった場合の対応と費用
- 切り替え後に確かめる項目（フォーム・決済など）と、問題が出たときの戻し方
- 保守契約に、PHPの版の切り替えと今後の脆弱性への対応が含まれるか

保守契約で確かめたい点は[ホームページ保守費用の相場](/blog/website-maintenance-cost-guide)で、WordPress全体のセキュリティ対策は[WordPressのセキュリティ対策](/blog/wordpress-security-hardening)で解説しています。

## よくある質問

### 12月31日を過ぎると、サイトは表示されなくなりますか？

すぐに表示されなくなるわけではありません。ただし、その後に見つかる脆弱性には原則として修正版が出ず、重大な脆弱性が見つかったときに更新で備えられなくなります。契約しているサーバー会社の告知もあわせて確かめてください。

### 8.3・8.4・8.5のどれに上げればよいですか？

WordPressが推奨するのはPHP 8.3以上です。新しい版ほどサポート期間は長くなりますが、テーマやプラグインが対応していなければ動きません。使っているテーマとプラグインが対応している範囲で、できるだけ新しい版を選ぶのが目安です。WordPress本体も、8.4なら6.7以降、8.5なら6.9以降に更新しておきます。

### WordPressを最新にすれば、PHPも新しくなりますか？

なりません。PHPはサーバー側の仕組みで、WordPressの更新とは別に、サーバーの管理画面などで切り替えます。共用のレンタルサーバーなら利用者が管理画面で、VPSや自社で管理するサーバーなら、その管理を担う担当者や委託先が切り替えます。

### サーバー会社が、古い版を自動で切り替えることはありますか？

エックスサーバーやロリポップは、推奨する版の変更や新しい版の提供を始めた際の告知で、使っている版は自動では切り替わらないとしています。一方、さくらのレンタルサーバは、サポートが終わった版で重大な脆弱性が見つかった場合などに、予告なく提供を終え、近い上位の版に切り替えることがあるとしています。急な切り替えで表示が崩れないよう、自社の計画で先に移っておくのが確実です。

### PHPの版の切り替えは、自社でやっても大丈夫ですか？

共用のレンタルサーバーなら、管理画面から自社で切り替えられます。ただし、独自の機能があるサイトや、ECサイト・会員サイトでは、不具合が売上や顧客対応に直結します。テスト環境での確認や、問題が出たときの対応に不安があれば、制作会社などに依頼する方が安全です。

### 移行の費用はどのくらいかかりますか？

サイトの作りで大きく変わります。版を上げるだけなら作業は小さく済みますが、独自の機能の修正や作り直しが要ると、費用も期間も大きくなります。見積もりを比べるときは、テスト環境での確認や戻し方まで含まれているかをそろえて見てください。

## まとめ

- PHP 8.2のサポートは2026年12月31日で終わり、以後に見つかる脆弱性には原則として修正版が出ない
- PHP2Shellでも、正式な修正版はサポート中の8.2以降にしか出なかった
- まずサイトヘルスなどで今の版を確かめ、8.2以前なら年内に移行を計画する
- 移行の方法は「版を上げる」「直してから上げる」「作り直す」の3つ。テーマ・プラグインの更新が続いているかが目安
- 切り替えはバックアップとテスト環境での確認を先に行い、委託先とは範囲と戻し方を文書で決める

